/** Auth schemes whose secret skillhook can invent (the sender is configured with it afterwards). */
export function skillhookManagesSecret(auth: NormalizedAuth): boolean {
  if (auth.type === "none") return false;
  if (auth.type === "hmac") return !auth.preset;
  return auth.type === "bearer" || auth.type === "basic";
}

/** Resolves `admin`, a skill name, or an ENV_VAR_NAME to the env var that holds the secret. */
export function resolveSecretName(ops: Ops, name: string): { env: string; skill?: Skill } {
  if (name === "admin") return { env: ADMIN_TOKEN_ENV };
  if (/^[A-Z_][A-Z0-9_]*$/.test(name)) return { env: name };
  if (isValidSkillName(name)) {
    const skill = ops.registry.get(name);
    if (skill && skill.auth.type !== "none") return { env: skill.auth.secret_env, skill };
    return { env: defaultSecretEnvFor(name), skill };
  }
  throw new Error(`"${name}" is neither a skill name nor an ENV_VAR_NAME`);
}

export interface SecretResult {
  env: string;
  /** The new value; only present when a value was generated by this call. */
  generated?: string;
  existed: boolean;
}

export function generateSecretFor(ops: Ops, name: string, options: { force?: boolean; bytes?: number } = {}): SecretResult {
  const { env } = resolveSecretName(ops, name);
  const existing = readEnvFile(ops.paths.envFile)[env];
  if (existing && !options.force) return { env, existed: true };
  const value = generateSecret(options.bytes ?? 32);
  upsertEnvVar(ops.paths.envFile, env, value);
  return { env, generated: value, existed: Boolean(existing) };
}

export function setSecret(ops: Ops, name: string, value: string): { env: string } {
  const { env } = resolveSecretName(ops, name);
  upsertEnvVar(ops.paths.envFile, env, value);
  return { env };
}

/** Makes sure a skill whose secret skillhook manages has one; provider-signed skills are left alone. */
export function ensureSkillSecret(ops: Ops, skill: Skill): SecretResult | undefined {
  if (!skillhookManagesSecret(skill.auth) || skill.auth.type === "none") return undefined;
  return generateSecretFor(ops, skill.auth.secret_env);
}

