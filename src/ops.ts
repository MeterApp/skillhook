export type UrlSource = "config" | "tailscale" | "server" | "local";

export async function resolveBaseUrl(ops: Ops, options: { prefer?: "public" | "local" } = {}): Promise<{ baseUrl: string; source: UrlSource }> {
  if (options.prefer !== "local") {
    if (ops.config.public_url) return { baseUrl: ops.config.public_url.replace(/\/$/, ""), source: "config" };
    if (findTailscale()) {
      const exposures = await currentExposures();
      const ours = exposures.find((e) => e.target.endsWith(`:${ops.config.port}`) && e.path === "/") ?? exposures.find((e) => e.target.endsWith(`:${ops.config.port}`));
      if (ours) return { baseUrl: ours.url, source: "tailscale" };
    }
    if (options.prefer === "public") throw new Error("No public URL yet. Run: skillhook expose tailscale");
  }
  const running = await findRunningServer(ops.paths);
  if (running) return { baseUrl: running.baseUrl, source: "server" };
  return { baseUrl: localBaseUrl({ host: ops.config.host, port: ops.config.port }), source: "local" };
}

export function webhookUrl(baseUrl: string, skillName: string): string {
  return `${baseUrl.replace(/\/$/, "")}/hooks/${skillName}`;
}

export interface SendResult {
  url: string;
  status: number;
  body: unknown;
  /** Names of the auth headers that were attached (values are never returned). */
  signedHeaders: string[];
  job?: Record<string, unknown>;
}

/** Signs a payload exactly like the configured sender would and POSTs it to `/hooks/<skill>`. */
export async function sendSignedWebhook(ops: Ops, input: { skill: Skill; payload: unknown; baseUrl: string; waitSeconds?: number; headers?: Record<string, string> }): Promise<SendResult> {
  const { skill } = input;
  const bodyText = typeof input.payload === "string" ? input.payload : JSON.stringify(input.payload ?? {});
  const rawBody = Buffer.from(bodyText);
  let signed: Record<string, string> = {};
  if (skill.auth.type !== "none") {
    const secret = ops.secrets()[skill.auth.secret_env];
    if (!secret) throw new Error(`Secret ${skill.auth.secret_env} is not set. Run: skillhook secret generate ${skill.name}`);
    signed = signRequest(skill.auth, secret, rawBody);
  }
  const url = `${webhookUrl(input.baseUrl, skill.name)}${input.waitSeconds ? `?wait=${input.waitSeconds}` : ""}`;
  let response: Response;
  try {
    response = await fetch(url, {
      method: "POST",
      headers: { "content-type": typeof input.payload === "string" ? "text/plain" : "application/json", "user-agent": "skillhook-send", ...signed, ...(input.headers ?? {}) },
      body: rawBody,
      signal: AbortSignal.timeout(((input.waitSeconds ?? 0) + 30) * 1000),
    });
  } catch (error) {
    const cause = (error as { cause?: { message?: string; code?: string } }).cause;
    const detail = cause?.message ?? errorMessage(error);
    const hint = url.startsWith("https://") ? " If this URL was exposed moments ago, Tailscale may still be fetching its TLS certificate: wait ~30s and retry, or check `skillhook expose status`." : " Is the server running? (skillhook serve / skillhook service status)";
    throw new Error(`POST ${url} failed: ${detail}.${hint}`);
  }
  const text = await response.text();
  let body: unknown = text;
  try {
    body = JSON.parse(text);
  } catch {
    /* not JSON */
  }
  const job = typeof body === "object" && body !== null && "job" in body ? ((body as { job: Record<string, unknown> }).job) : undefined;
  return { url, status: response.status, body, signedHeaders: Object.keys(signed), job };
}

