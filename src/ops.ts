export interface CreateSkillInput {
  name: string;
  description: string;
  instructions?: string;
  runner?: RunnerName;
  model?: string;
  effort?: string;
  authType?: AuthType;
  secretEnv?: string;
  cwd?: string;
  timeoutSeconds?: number;
  when?: unknown[];
  env?: string[];
  overwrite?: boolean;
  /** Skip creating a secret (for provider-signed auth you still have to `secret set` it). */
  noSecret?: boolean;
}

export interface CreateSkillResult {
  skill: Skill;
  file: string;
  created: boolean;
  secret?: SecretResult;
  /** What the sender must do to authenticate, for humans. */
  authNote: string;
}

export function createSkill(ops: Ops, input: CreateSkillInput): CreateSkillResult {
  if (!isValidSkillName(input.name)) throw new Error(`Invalid skill name "${input.name}": use 1-64 lowercase letters, digits and single hyphens`);
  if (input.authType && !AUTH_TYPES.includes(input.authType)) throw new Error(`Unknown auth type "${input.authType}". Known: ${AUTH_TYPES.join(", ")}`);
  const dir = path.join(ops.paths.skillsDir, input.name);
  const file = skillFile(dir);
  if (existsSync(file) && !input.overwrite) throw new Error(`Skill "${input.name}" already exists at ${file} (pass overwrite to replace it)`);
  let content = renderSkillTemplate({ name: input.name, description: input.description, runner: input.runner, model: input.model, authType: input.authType, cwd: input.cwd, instructions: input.instructions });
  // Extra structured fields go through the frontmatter parser so the file stays valid YAML.
  if (input.effort || input.timeoutSeconds || input.secretEnv || input.when?.length || input.env?.length) {
    const fm = parseFrontmatter(content);
    const block = (fm.data.skillhook ?? {}) as Record<string, unknown>;
    if (input.effort) block.effort = input.effort;
    if (input.timeoutSeconds) block.timeout_seconds = input.timeoutSeconds;
    if (input.secretEnv) block.auth = { ...((block.auth as Record<string, unknown>) ?? { type: input.authType ?? "bearer" }), secret_env: input.secretEnv };
    if (input.when?.length) block.when = input.when;
    if (input.env?.length) block.env = input.env;
    fm.data.skillhook = block;
    content = stringifyFrontmatter(fm.data, fm.body);
  }
  const skill = parseSkillDocument(content, dir); // validate before touching disk
  mkdirSync(dir, { recursive: true });
  writeFileSync(file, content);
  const loaded = ops.registry.get(input.name) ?? skill;
  const secret = input.noSecret ? undefined : ensureSkillSecret(ops, loaded);
  return { skill: loaded, file, created: true, secret, authNote: authNoteFor(loaded, secret) };
}

export function authNoteFor(skill: Skill, secret?: SecretResult): string {
  const auth = skill.auth;
  if (auth.type === "none") return "No authentication: anyone with the URL can trigger this skill. Consider allow_ips or a bearer token.";
  const envName = auth.secret_env;
  if (skillhookManagesSecret(auth)) {
    const how = auth.type === "bearer" ? (auth.header === "authorization" ? `Authorization: Bearer <secret>` : `${auth.header}: <secret>`) : auth.type === "basic" ? "HTTP Basic (user:password)" : `HMAC-${(auth as { algorithm: string }).algorithm.toUpperCase()} of the body in ${(auth as { header: string }).header}`;
    const state = secret?.generated ? "A fresh secret was generated" : `Secret ${envName} ${secret?.existed ? "already exists" : "is not set"}`;
    return `${state} in .env. Configure the sender to send ${how}. Show or rotate it with: skillhook secret generate ${skill.name} --force`;
  }
  return `Paste the signing secret from ${auth.type === "standard-webhooks" ? auth.preset ?? "the provider" : auth.type === "hmac" ? auth.preset ?? "the provider" : auth.type} into skillhook: skillhook secret set ${envName}`;
}

export function addExampleSkill(ops: Ops, exampleName: string, asName = exampleName): CreateSkillResult {
  const example = findExample(exampleName);
  if (!example) throw new Error(`No bundled example named "${exampleName}". Run: skillhook skills examples`);
  if (!isValidSkillName(asName)) throw new Error(`Invalid skill name "${asName}"`);
  const dir = path.join(ops.paths.skillsDir, asName);
  if (existsSync(dir)) throw new Error(`Skill "${asName}" already exists at ${dir}`);
  cpSync(example.dir, dir, { recursive: true });
  if (asName !== exampleName) {
    const text = readFileSync(skillFile(dir), "utf8").replace(/^name:\s*.*$/m, `name: ${asName}`);
    writeFileSync(skillFile(dir), text);
  }
  const skill = ops.registry.get(asName);
  if (!skill) throw new Error(`Example copied but failed to load from ${dir}`);
  const secret = ensureSkillSecret(ops, skill);
  return { skill, file: skillFile(dir), created: true, secret, authNote: authNoteFor(skill, secret) };
}

