export interface Ops {
  paths: Paths;
  config: Config;
  secrets: () => Secrets;
  /** Secrets from the .env file only. */
  fileSecrets: () => Secrets;
  registry: SkillRegistry;
  store: JobStore;
  logger: Logger;
}

export function createOps(paths: Paths, options: { env?: NodeJS.ProcessEnv; logger?: Logger; config?: Config } = {}): Ops {
  const config = options.config ?? loadConfig(paths);
  return {
    paths,
    config,
    secrets: () => loadSecrets(paths, options.env ?? process.env),
    fileSecrets: () => readEnvFile(paths.envFile),
    registry: new SkillRegistry(paths.skillsDir, { projects: configProjects(paths) }),
    store: new JobStore(paths.jobsDir, { maxJobs: config.jobs.max_jobs, dedupeWindowSeconds: config.jobs.dedupe_window_seconds }),
    logger: options.logger ?? silentLogger,
  };
}

