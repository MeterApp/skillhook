// Sessions live in the profile that created them. Fresh jobs may use a pool; actual resumes must not move.
import { getAccount, listAccounts, poolFor } from "./accounts.js";
import type { Config } from "./config.js";
import type { JobRecord } from "./jobs.js";
import { getRunner } from "./runners/index.js";
import type { Skill } from "./skills.js";

export function resumeAccount(job: JobRecord, original: JobRecord | undefined, skill: Skill, config: Config, home: string, directEnv: Record<string, string>): string | undefined {
  if (!job.resume) return undefined;
  const fail = () => new Error(`Cannot safely resume session ${job.resume!.session_id}: its original account is unavailable or unknown; restore the original profile or explicitly replay the job as fresh work`);
  if (job.runner !== job.resume.runner) throw fail();
  const name = job.account_requested ?? original?.account;
  if (name) {
    const account = getAccount(config, home, name);
    if (!account || account.runner !== job.runner) throw fail();
    return name; // Disabled/logged-out/limited accounts fail pre-flight, without another account or runner.
  }
  if (!original?.resume_command || !original.cwd) throw fail();
  const command = getRunner(job.runner).resumeCommand;
  if (!command) throw fail();
  // Compare complete commands generated by our runners. Never execute or parse a historical shell command.
  const accounts = listAccounts(config, home).filter((account) => account.runner === job.runner);
  accounts.sort((a, b) => Number(a.disabled) - Number(b.disabled));
  for (const account of accounts) {
    const named = command(job.resume.session_id, original.cwd, { SKILLHOOK_ACCOUNT: account.name });
    const legacy = command(job.resume.session_id, original.cwd, account.defaultDir ? {} : { [job.runner === "claude" ? "CLAUDE_CONFIG_DIR" : "CODEX_HOME"]: account.dir });
    if (original.resume_command === named || (account.kind === "login" && original.resume_command === legacy)) return account.name;
  }
  // Backwards compatibility for installations without a pool: the current direct profile must still match exactly.
  if (!poolFor(skill, config, job.runner).length && original.resume_command === command(job.resume.session_id, original.cwd, directEnv)) return undefined;
  throw fail();
}
